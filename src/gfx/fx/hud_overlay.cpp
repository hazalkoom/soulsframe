constexpr uint32_t pack_rgba(uint8_t r, uint8_t g, uint8_t b, uint8_t a) noexcept {
  return static_cast<uint32_t>(r) | (static_cast<uint32_t>(g) << 8U) |
         (static_cast<uint32_t>(b) << 16U) | (static_cast<uint32_t>(a) << 24U);
}

const char* effective_flag_label(bool mod_active, bool configured, bool on) noexcept {
  if (!mod_active) {
    return configured && on ? "PAUSED" : "OFF";
  }
  return on ? "ON" : "OFF";
}

