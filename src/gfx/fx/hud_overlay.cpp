std::vector<std::string> format_hud_lines(const HudSnapshot& snap) {
  std::vector<std::string> lines;
  if (snap.show_fps) {
    std::array<char, 128> buf{};
    if (snap.mod_active) {
      std::snprintf(buf.data(), buf.size(), "SF v%s | %5.1f FPS | %4.1fms | 1%% %4.1fms",
                    sf::kVersionString, snap.fps, snap.avg_ms, snap.p1_low_ms);
    } else {
      std::snprintf(buf.data(), buf.size(), "PAUSED | SF v%s | %5.1f FPS | %4.1fms | 1%% %4.1fms",
                    sf::kVersionString, snap.fps, snap.avg_ms, snap.p1_low_ms);
    }
    lines.emplace_back(buf.data());
  }

  if (snap.show_status) {
    std::array<char, 160> buf{};
    std::string cap_label = "OFF";
    if (snap.frame_cap_fps > 0U && snap.frame_cap_on) {
      cap_label = snap.mod_active ? std::to_string(snap.frame_cap_fps) : "PAUSED";
    }
    std::snprintf(
        buf.data(), buf.size(), "[%s] MOD:%s  [%s] FSR:%s  [%s] PT:%s  [%s] CAP:%s  [%s] HUD",
        snap.key_mod.c_str(), snap.mod_active ? "ON" : "OFF", snap.key_upscaler.c_str(),
        effective_flag_label(snap.mod_active, snap.upscaler_configured, snap.upscaler_on),
        snap.key_particles.c_str(),
        effective_flag_label(snap.mod_active, snap.particles_configured, snap.particles_on),
        snap.key_cap.c_str(), cap_label.c_str(), snap.key_overlay.c_str());
    lines.emplace_back(buf.data());
  }
  return lines;
}

HudBitmap rasterize_hud(const std::vector<std::string>& lines, bool mod_active,
                        uint32_t opacity_percent) {
  if (lines.empty()) {
    return {};
  }
  size_t max_chars = 0U;
  for (const auto& line : lines) {
    max_chars = std::max(max_chars, line.size());
  }
  if (max_chars == 0U) {
    return {};
  }

  constexpr uint32_t kPadX = 4U;
  constexpr uint32_t kPadY = 4U;
  constexpr uint32_t kLineStep = 10U;
  const uint32_t width = static_cast<uint32_t>(max_chars) * 8U + (kPadX * 2U);
  const uint32_t height = static_cast<uint32_t>(lines.size()) * kLineStep - 2U + (kPadY * 2U);

  const uint32_t clamped_opacity = std::min(opacity_percent, 100U);
  const auto bg_alpha = static_cast<uint8_t>((clamped_opacity * 235U) / 100U);
  const uint32_t bg_color = pack_rgba(14U, 16U, 22U, bg_alpha);
  const uint32_t border_color =
      mod_active ? pack_rgba(220U, 178U, 88U, 240U) : pack_rgba(218U, 96U, 64U, 240U);
  const uint32_t shadow_color = pack_rgba(0U, 0U, 0U, 220U);
  const uint32_t primary_text =
      mod_active ? pack_rgba(245U, 242U, 232U, 255U) : pack_rgba(255U, 196U, 172U, 255U);
  const uint32_t secondary_text = pack_rgba(202U, 214U, 226U, 255U);

  HudBitmap bmp{.width = width,
                .height = height,
                .rgba = std::vector<uint32_t>(static_cast<size_t>(width) * height, bg_color)};

  for (uint32_t x = 0U; x < width; ++x) {
    bmp.rgba[x] = border_color;
    bmp.rgba[static_cast<size_t>(height - 1U) * width + x] = border_color;
  }
  for (uint32_t y = 0U; y < height; ++y) {
    bmp.rgba[static_cast<size_t>(y) * width] = border_color;
    bmp.rgba[static_cast<size_t>(y) * width + (width - 1U)] = border_color;
  }

  for (size_t line_idx = 0U; line_idx < lines.size(); ++line_idx) {
    const uint32_t fg = (line_idx == 0U) ? primary_text : secondary_text;
    const uint32_t base_y = kPadY + static_cast<uint32_t>(line_idx) * kLineStep;
    const std::string& text = lines[line_idx];
    for (size_t col_idx = 0U; col_idx < text.size(); ++col_idx) {
      const auto ch = static_cast<unsigned char>(text[col_idx]);
      const size_t glyph_idx = (ch >= 0x20U && ch <= 0x7EU) ? static_cast<size_t>(ch - 0x20U) : 0U;
      const auto& glyph = kFont8x8[glyph_idx];
      const uint32_t base_x = kPadX + static_cast<uint32_t>(col_idx) * 8U;

      for (uint32_t row = 0U; row < 8U; ++row) {
        const uint8_t bits = glyph[row];
        for (uint32_t col = 0U; col < 8U; ++col) {
          if ((bits & (0x80U >> col)) == 0U) {
            continue;
          }
          const uint32_t px = base_x + col;
          const uint32_t py = base_y + row;
          if (px + 1U < width && py + 1U < height) {
            bmp.rgba[static_cast<size_t>(py + 1U) * width + (px + 1U)] = shadow_color;
          }
          if (px < width && py < height) {
            bmp.rgba[static_cast<size_t>(py) * width + px] = fg;
          }
        }
      }
    }
  }
  return bmp;
}

HudRect compute_hud_rect(uint32_t backbuffer_w, uint32_t backbuffer_h, uint32_t bmp_w,
                         uint32_t bmp_h, uint32_t scale, std::string_view position,
                         uint32_t margin_px) noexcept {
  if (backbuffer_w == 0U || backbuffer_h == 0U || bmp_w == 0U || bmp_h == 0U) {
    return {};
  }
  const uint32_t clamped_scale = std::clamp(scale, 1U, 4U);
  uint32_t draw_w = bmp_w * clamped_scale;
  uint32_t draw_h = bmp_h * clamped_scale;

  const uint32_t avail_w =
      (backbuffer_w > margin_px * 2U) ? (backbuffer_w - margin_px * 2U) : backbuffer_w;
  const uint32_t avail_h =
      (backbuffer_h > margin_px * 2U) ? (backbuffer_h - margin_px * 2U) : backbuffer_h;
  if (draw_w > avail_w) {
    draw_h = std::max(1U, (draw_h * avail_w) / draw_w);
    draw_w = avail_w;
  }
  if (draw_h > avail_h) {
    draw_w = std::max(1U, (draw_w * avail_h) / draw_h);
    draw_h = avail_h;
  }

  const uint32_t eff_margin_x = (draw_w + margin_px <= backbuffer_w) ? margin_px : 0U;
  const uint32_t eff_margin_y = (draw_h + margin_px <= backbuffer_h) ? margin_px : 0U;

  float x = static_cast<float>(eff_margin_x);
  float y = static_cast<float>(eff_margin_y);
  if (position == "top_right" || position == "bottom_right") {
    x = static_cast<float>(backbuffer_w - draw_w - eff_margin_x);
  }
  if (position == "bottom_left" || position == "bottom_right") {
    y = static_cast<float>(backbuffer_h - draw_h - eff_margin_y);
  }

  return {
      .x = x, .y = y, .width = static_cast<float>(draw_w), .height = static_cast<float>(draw_h)};
}

