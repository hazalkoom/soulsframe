#!/usr/bin/env python3
"""Offline texture-pack baker for SoulsFrame M9.

Why: the in-game hook only matches `key -> file.dds` pairs; this tool turns a folder of
DDS files named by key (e.g. `0123456789abcdef.dds`, optionally in sub-folders) into a
validated `manifest.txt`, and can extract keys from a `dump_keys = true` log so modders
know which textures exist.

Usage:
  bake_textures.py build <pack_dir>          # validate DDS files, write manifest.txt
  bake_textures.py keys <soulsframe.log>     # list keys dumped by TextureModule
"""

from __future__ import annotations

import argparse
import re
import struct
import sys
from pathlib import Path

KEY_RE = re.compile(r"^[0-9a-fA-F]{16}$")
LOG_RE = re.compile(r"TextureModule key ([0-9a-f]{16}) (\d+)x(\d+) fmt=(\d+) mips=(\d+)")
FOURCC = {b"DXT1": 71, b"DXT3": 74, b"DXT5": 77, b"ATI1": 80, b"BC4U": 80, b"ATI2": 83, b"BC5U": 83}
BC8 = {71, 72, 80, 81}
BC16 = {74, 75, 77, 78, 83, 84, 95, 96, 98, 99}
RGBA = {28, 29, 87, 91}


def chain_bytes(fmt: int, w: int, h: int, mips: int) -> int:
    """Mirrors sf::tex::mip_chain_bytes()."""
    total = 0
    for _ in range(mips):
        if fmt in BC8 or fmt in BC16:
            total += ((w + 3) // 4) * ((h + 3) // 4) * (8 if fmt in BC8 else 16)
        else:
            total += w * h * 4
        w, h = max(1, w // 2), max(1, h // 2)
    return total


def check_dds(data: bytes) -> str | None:
    """Returns None if valid, else a reason. Mirrors sf::tex::parse_dds()."""
    if len(data) < 128 or data[:4] != b"DDS " or struct.unpack_from("<I", data, 4)[0] != 124:
        return "bad DDS header"
    h, w = struct.unpack_from("<II", data, 12)
    mips = struct.unpack_from("<I", data, 28)[0] or 1
    pf_flags = struct.unpack_from("<I", data, 80)[0]
    cc = data[84:88]
    if struct.unpack_from("<I", data, 112)[0] & 0x200200:
        return "cubemap/volume not supported"
    if not (0 < w <= 16384 and 0 < h <= 16384) or mips > 15:
        return "dimensions or mip count out of range"
    off, fmt = 128, 0
    if pf_flags & 4 and cc == b"DX10":
        if len(data) < 148:
            return "truncated DX10 header"
        fmt, dim, _, arr = struct.unpack_from("<IIII", data, 128)
        if dim != 3 or arr > 1:
            return "DX10 DDS must be a single 2D texture"
        off = 148
    elif pf_flags & 4:
        fmt = FOURCC.get(cc, 0)
    elif pf_flags & 0x40 and struct.unpack_from("<I", data, 88)[0] == 32:
        fmt = {0xFF: 28, 0xFF0000: 87}.get(struct.unpack_from("<I", data, 92)[0], 0)
    if fmt not in BC8 | BC16 | RGBA:
        return "unsupported pixel format (use BC1-BC7 or RGBA8)"
    if len(data) - off < chain_bytes(fmt, w, h, mips):
        return "payload truncated"
    return None


def build(pack: Path) -> int:
    lines, errors = ["# Generated by tools/py/bake_textures.py"], 0
    for dds in sorted(pack.rglob("*.dds")):
        if not KEY_RE.match(dds.stem):
            print(f"skip {dds}: name is not a 16-hex-digit key", file=sys.stderr)
            continue
        reason = check_dds(dds.read_bytes())
        if reason:
            print(f"error {dds}: {reason}", file=sys.stderr)
            errors += 1
            continue
        lines.append(f"{dds.stem.lower()} = {dds.relative_to(pack).as_posix()}")
    (pack / "manifest.txt").write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"wrote {len(lines) - 1} entries to {pack / 'manifest.txt'} ({errors} errors)")
    return 1 if errors else 0


def keys(log: Path) -> int:
    for m in LOG_RE.finditer(log.read_text(encoding="utf-8", errors="replace")):
        print(f"{m[1]}  {m[2]}x{m[3]}  fmt={m[4]}  mips={m[5]}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build").add_argument("pack_dir", type=Path)
    sub.add_parser("keys").add_argument("log", type=Path)
    a = ap.parse_args()
    return build(a.pack_dir) if a.cmd == "build" else keys(a.log)


if __name__ == "__main__":
    sys.exit(main())
